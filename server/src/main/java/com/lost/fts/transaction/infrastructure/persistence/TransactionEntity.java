package com.lost.fts.transaction.infrastructure.persistence;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.Instant;
import java.util.Locale;

import com.lost.fts.account.infrastructure.persistence.AccountEntity;
import com.lost.fts.beneficiary.infrastructure.persistence.BeneficiaryEntity;
import com.lost.fts.customer.infrastructure.persistence.CustomerDeviceEntity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;

@Entity
@Table(name = "transactions", uniqueConstraints = {
        @UniqueConstraint(name = "uktransactionstransactionref", columnNames = "transactionref"),
        @UniqueConstraint(name = "uktransactionssourceexternalref", columnNames = {
                "sourcesystem",
                "externaltransactionref"
        })
}, indexes = {
        @Index(name = "idxtransactionssourcetime", columnList = "sourceaccountid, occurredat"),
        @Index(name = "idxtransactionsdestinationtime", columnList = "destinationaccountid, occurredat"),
        @Index(name = "idxtransactionsstatustime", columnList = "status, occurredat"),
        @Index(name = "idxtransactionsbeneficiary", columnList = "beneficiaryid")
})
public class TransactionEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    // Unique reference generated by our EWS platform.
    @Column(name = "transactionref", nullable = false, length = 64)
    private String transactionRef;

    // Account sending the money, if held in our system.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "sourceaccountid", foreignKey = @ForeignKey(name = "fktransactionssourceaccount"))
    private AccountEntity sourceAccount;

    // Account receiving the money, if held in our system.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "destinationaccountid", foreignKey = @ForeignKey(name = "fktransactionsdestinationaccount"))
    private AccountEntity destinationAccount;

    // Optional saved beneficiary for outgoing payments.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "beneficiaryid", foreignKey = @ForeignKey(name = "fktransactionsbeneficiary"))
    private BeneficiaryEntity beneficiary;

    // Optional device association for activity initiated by a customer.
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "customerdeviceid", foreignKey = @ForeignKey(name = "fktransactionscustomerdevice"))
    private CustomerDeviceEntity customerDevice;

    // System that originally supplied the transaction.
    @Column(name = "sourcesystem", nullable = false, length = 64)
    private String sourceSystem;

    // External provider's reference, when available.
    @Column(name = "externaltransactionref", length = 128)
    private String externalTransactionRef;

    @Enumerated(EnumType.STRING)
    @Column(name = "transactiontype", nullable = false, length = 30)
    private TransactionType transactionType;

    @Enumerated(EnumType.STRING)
    @Column(name = "channel", nullable = false, length = 30)
    private TransactionChannel channel;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private TransactionStatus status = TransactionStatus.PENDING;

    // Never use double or float for monetary values.
    @Column(name = "amount", nullable = false, precision = 19, scale = 4)
    private BigDecimal amount;

    @Column(name = "currency", nullable = false, length = 3, columnDefinition = "CHAR(3)")
    private String currency;

    // Tokenized external counterparty reference, if needed.
    @Column(name = "counterpartyreferencetoken", length = 128)
    private String counterpartyReferenceToken;

    // Display-only masked value; never the raw sensitive identifier.
    @Column(name = "counterpartymasked", length = 100)
    private String counterpartyMasked;

    // When the financial event actually occurred.
    @Column(name = "occurredat", nullable = false)
    private Instant occurredAt;

    // When processing reached a completed, failed or cancelled state.
    @Column(name = "processedat")
    private Instant processedAt;

    @Column(name = "createdat", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updatedat", nullable = false)
    private Instant updatedAt;

    protected TransactionEntity() {
        // Required by JPA
    }

    public TransactionEntity(
            String transactionRef,
            AccountEntity sourceAccount,
            AccountEntity destinationAccount,
            BeneficiaryEntity beneficiary,
            CustomerDeviceEntity customerDevice,
            String sourceSystem,
            String externalTransactionRef,
            TransactionType transactionType,
            TransactionChannel channel,
            BigDecimal amount,
            String currency,
            String counterpartyReferenceToken,
            String counterpartyMasked,
            Instant occurredAt) {

        if (isBlank(transactionRef)) {
            throw new IllegalArgumentException(
                    "Transaction reference is required");
        }

        if (sourceAccount == null && destinationAccount == null) {
            throw new IllegalArgumentException(
                    "At least one internal account is required");
        }

        if (beneficiary != null && sourceAccount == null) {
            throw new IllegalArgumentException(
                    "A saved beneficiary requires a source account");
        }

        if (customerDevice != null && sourceAccount == null) {
            throw new IllegalArgumentException(
                    "A customer device requires a source account");
        }

        if (isBlank(sourceSystem)) {
            throw new IllegalArgumentException(
                    "Source system is required");
        }

        if (transactionType == null
                || channel == null
                || occurredAt == null) {
            throw new IllegalArgumentException(
                    "Transaction type, channel and occurrence time are required");
        }

        this.transactionRef = transactionRef.trim();
        this.sourceAccount = sourceAccount;
        this.destinationAccount = destinationAccount;
        this.beneficiary = beneficiary;
        this.customerDevice = customerDevice;
        this.sourceSystem = sourceSystem.trim();
        this.externalTransactionRef = normalizeOptional(externalTransactionRef);
        this.transactionType = transactionType;
        this.channel = channel;
        this.amount = validateAmount(amount);
        this.currency = validateCurrency(currency);
        this.counterpartyReferenceToken = normalizeOptional(counterpartyReferenceToken);
        this.counterpartyMasked = normalizeOptional(counterpartyMasked);
        this.occurredAt = occurredAt;
        this.status = TransactionStatus.PENDING;
    }

    public void markProcessing() {
        if (status != TransactionStatus.PENDING) {
            throw new IllegalStateException(
                    "Only pending transactions can begin processing");
        }

        status = TransactionStatus.PROCESSING;
    }

    public void markCompleted(Instant processedAt) {
        requireProcessingState();
        this.processedAt = requireTimestamp(processedAt);
        this.status = TransactionStatus.COMPLETED;
    }

    public void markFailed(Instant processedAt) {
        requireProcessingState();
        this.processedAt = requireTimestamp(processedAt);
        this.status = TransactionStatus.FAILED;
    }

    public void markCancelled(Instant processedAt) {
        requireProcessingState();
        this.processedAt = requireTimestamp(processedAt);
        this.status = TransactionStatus.CANCELLED;
    }

    private void requireProcessingState() {
        if (status != TransactionStatus.PENDING
                && status != TransactionStatus.PROCESSING) {
            throw new IllegalStateException(
                    "Transaction cannot transition from status " + status);
        }
    }

    private static Instant requireTimestamp(Instant timestamp) {
        if (timestamp == null) {
            throw new IllegalArgumentException(
                    "Processing timestamp is required");
        }

        return timestamp;
    }

    private static BigDecimal validateAmount(BigDecimal amount) {
        if (amount == null || amount.signum() <= 0) {
            throw new IllegalArgumentException(
                    "Transaction amount must be greater than zero");
        }

        try {
            BigDecimal normalized = amount.setScale(4, RoundingMode.UNNECESSARY);

            if (normalized.precision() > 19) {
                throw new IllegalArgumentException(
                        "Transaction amount exceeds DECIMAL(19,4) precision");
            }

            return normalized;
        } catch (ArithmeticException ex) {
            throw new IllegalArgumentException(
                    "Transaction amount supports at most four decimal places",
                    ex);
        }
    }

    private static String validateCurrency(String currency) {
        if (currency == null) {
            throw new IllegalArgumentException(
                    "Currency is required");
        }

        String normalized = currency.trim().toUpperCase(Locale.ROOT);

        if (!normalized.matches("[A-Z]{3}")) {
            throw new IllegalArgumentException(
                    "Currency must be a three-letter code");
        }

        return normalized;
    }

    private static String normalizeOptional(String value) {
        if (value == null || value.isBlank()) {
            return null;
        }

        return value.trim();
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }

    @PrePersist
    protected void onCreate() {
        Instant now = Instant.now();
        createdAt = now;
        updatedAt = now;
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = Instant.now();
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getTransactionRef() {
        return transactionRef;
    }

    public void setTransactionRef(String transactionRef) {
        this.transactionRef = transactionRef;
    }

    public AccountEntity getSourceAccount() {
        return sourceAccount;
    }

    public void setSourceAccount(AccountEntity sourceAccount) {
        this.sourceAccount = sourceAccount;
    }

    public AccountEntity getDestinationAccount() {
        return destinationAccount;
    }

    public void setDestinationAccount(AccountEntity destinationAccount) {
        this.destinationAccount = destinationAccount;
    }

    public BeneficiaryEntity getBeneficiary() {
        return beneficiary;
    }

    public void setBeneficiary(BeneficiaryEntity beneficiary) {
        this.beneficiary = beneficiary;
    }

    public CustomerDeviceEntity getCustomerDevice() {
        return customerDevice;
    }

    public void setCustomerDevice(CustomerDeviceEntity customerDevice) {
        this.customerDevice = customerDevice;
    }

    public String getSourceSystem() {
        return sourceSystem;
    }

    public void setSourceSystem(String sourceSystem) {
        this.sourceSystem = sourceSystem;
    }

    public String getExternalTransactionRef() {
        return externalTransactionRef;
    }

    public void setExternalTransactionRef(String externalTransactionRef) {
        this.externalTransactionRef = externalTransactionRef;
    }

    public TransactionType getTransactionType() {
        return transactionType;
    }

    public void setTransactionType(TransactionType transactionType) {
        this.transactionType = transactionType;
    }

    public TransactionChannel getChannel() {
        return channel;
    }

    public void setChannel(TransactionChannel channel) {
        this.channel = channel;
    }

    public TransactionStatus getStatus() {
        return status;
    }

    public void setStatus(TransactionStatus status) {
        this.status = status;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public void setAmount(BigDecimal amount) {
        this.amount = amount;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public String getCounterpartyReferenceToken() {
        return counterpartyReferenceToken;
    }

    public void setCounterpartyReferenceToken(String counterpartyReferenceToken) {
        this.counterpartyReferenceToken = counterpartyReferenceToken;
    }

    public String getCounterpartyMasked() {
        return counterpartyMasked;
    }

    public void setCounterpartyMasked(String counterpartyMasked) {
        this.counterpartyMasked = counterpartyMasked;
    }

    public Instant getOccurredAt() {
        return occurredAt;
    }

    public void setOccurredAt(Instant occurredAt) {
        this.occurredAt = occurredAt;
    }

    public Instant getProcessedAt() {
        return processedAt;
    }

    public void setProcessedAt(Instant processedAt) {
        this.processedAt = processedAt;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }

}
