package com.lost.fts.alert.infrastructure.persistence;

import java.time.Instant;

import com.lost.fts.riskassessment.infrastructure.persistence.AssessmentStatus;
import com.lost.fts.riskassessment.infrastructure.persistence.RiskAssessmentEntity;
import com.lost.fts.rulemanagement.infrastructure.persistence.RuleDomain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.ForeignKey;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import jakarta.persistence.Version;

@Entity
@Table(name = "alerts", uniqueConstraints = {
        @UniqueConstraint(name = "ukalertsalertref", columnNames = "alertref"),
        @UniqueConstraint(name = "ukalertsdeduplicationkey", columnNames = "deduplicationkey")
}, indexes = {
        @Index(name = "idxalertsstatusseveritycreated", columnList = "status, severity, createdat"),
        @Index(name = "idxalertsassessment", columnList = "riskassessmentid"),
        @Index(name = "idxalertsassigneestatus", columnList = "assignedto, status")
})
public class AlertEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "alertref", nullable = false, length = 64)
    private String alertRef;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "riskassessmentid", nullable = false, foreignKey = @ForeignKey(name = "fkalertsriskassessment"))
    private RiskAssessmentEntity riskAssessment;

    // Stable identifier for the type or pattern represented by this alert.
    @Column(name = "correlationkey", nullable = false, length = 128)
    private String correlationKey;

    // Deterministically generated by the application for duplicate prevention.
    @Column(name = "deduplicationkey", nullable = false, length = 160)
    private String deduplicationKey;

    @Enumerated(EnumType.STRING)
    @Column(name = "alertdomain", nullable = false, length = 40)
    private RuleDomain domain;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private AlertSeverity severity;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private AlertStatus status = AlertStatus.NEW;

    @Column(nullable = false, length = 200)
    private String title;

    @Column(length = 2000)
    private String description;

    @Column(name = "assignedto", length = 100)
    private String assignedTo;

    @Column(name = "acknowledgedby", length = 100)
    private String acknowledgedBy;

    @Column(name = "acknowledgedat")
    private Instant acknowledgedAt;

    @Column(name = "sladueat")
    private Instant slaDueAt;

    @Column(name = "resolvedby", length = 100)
    private String resolvedBy;

    @Column(name = "resolutioncode", length = 100)
    private String resolutionCode;

    @Column(name = "resolvedat")
    private Instant resolvedAt;

    @Column(name = "createdby", nullable = false, length = 100)
    private String createdBy;

    @Column(name = "createdat", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updatedat", nullable = false)
    private Instant updatedAt;

    @Version
    @Column(name = "rowversion", nullable = false)
    private Long rowVersion;

    protected AlertEntity() {
        // Required by JPA
    }

    public AlertEntity(
            String alertRef,
            RiskAssessmentEntity riskAssessment,
            String correlationKey,
            String deduplicationKey,
            RuleDomain domain,
            AlertSeverity severity,
            String title,
            String description,
            String createdBy,
            Instant slaDueAt) {

        if (isBlank(alertRef)
                || isBlank(correlationKey)
                || isBlank(deduplicationKey)) {
            throw new IllegalArgumentException(
                    "Alert reference and deduplication keys are required");
        }

        if (riskAssessment == null
                || riskAssessment.getStatus() != AssessmentStatus.COMPLETED) {
            throw new IllegalArgumentException(
                    "A completed risk assessment is required");
        }

        if (domain == null || severity == null || isBlank(title)
                || isBlank(createdBy)) {
            throw new IllegalArgumentException(
                    "Domain, severity, title and creator are required");
        }

        this.alertRef = alertRef.trim();
        this.riskAssessment = riskAssessment;
        this.correlationKey = correlationKey.trim();
        this.deduplicationKey = deduplicationKey.trim();
        this.domain = domain;
        this.severity = severity;
        this.title = title.trim();
        this.description = normalizeOptional(description);
        this.createdBy = createdBy.trim();
        this.slaDueAt = slaDueAt;
        this.status = AlertStatus.NEW;
    }

    public void assignTo(String username) {
        ensureOpenForWork();

        if (isBlank(username)) {
            throw new IllegalArgumentException(
                    "Assignee is required");
        }

        this.assignedTo = username.trim();
    }

    public void acknowledge(String actor, Instant actionTime) {
        if (status != AlertStatus.NEW) {
            throw new IllegalStateException(
                    "Only new alerts can be acknowledged");
        }

        validateActorAndTime(actor, actionTime);

        this.acknowledgedBy = actor.trim();
        this.acknowledgedAt = actionTime;
        this.status = AlertStatus.ACKNOWLEDGED;
    }

    public void startInvestigation(String actor) {
        if (status != AlertStatus.ACKNOWLEDGED
                && status != AlertStatus.ESCALATED) {
            throw new IllegalStateException(
                    "Alert must be acknowledged or escalated first");
        }

        if (isBlank(actor)) {
            throw new IllegalArgumentException(
                    "Investigator is required");
        }

        this.assignedTo = actor.trim();
        this.status = AlertStatus.UNDERINVESTIGATION;
    }

    public void escalate() {
        if (status != AlertStatus.NEW
                && status != AlertStatus.ACKNOWLEDGED
                && status != AlertStatus.UNDERINVESTIGATION) {
            throw new IllegalStateException(
                    "Alert cannot be escalated from status " + status);
        }

        this.status = AlertStatus.ESCALATED;
    }

    public void resolve(
            String resolutionCode,
            String actor,
            Instant resolvedAt) {

        if (status != AlertStatus.UNDERINVESTIGATION
                && status != AlertStatus.ESCALATED) {
            throw new IllegalStateException(
                    "Only investigated or escalated alerts can be resolved");
        }

        if (isBlank(resolutionCode)) {
            throw new IllegalArgumentException(
                    "Resolution code is required");
        }

        validateActorAndTime(actor, resolvedAt);

        this.resolutionCode = resolutionCode.trim();
        this.resolvedBy = actor.trim();
        this.resolvedAt = resolvedAt;
        this.status = AlertStatus.RESOLVED;
    }

    public void markFalsePositive(
            String resolutionCode,
            String actor,
            Instant resolvedAt) {

        if (status != AlertStatus.UNDERINVESTIGATION
                && status != AlertStatus.ESCALATED) {
            throw new IllegalStateException(
                    "Only investigated or escalated alerts can be marked false positive");
        }

        if (isBlank(resolutionCode)) {
            throw new IllegalArgumentException(
                    "Resolution code is required");
        }

        validateActorAndTime(actor, resolvedAt);

        this.resolutionCode = resolutionCode.trim();
        this.resolvedBy = actor.trim();
        this.resolvedAt = resolvedAt;
        this.status = AlertStatus.FALSEPOSITIVE;
    }

    public void close() {
        if (status != AlertStatus.RESOLVED
                && status != AlertStatus.FALSEPOSITIVE) {
            throw new IllegalStateException(
                    "Only resolved or false-positive alerts can be closed");
        }

        this.status = AlertStatus.CLOSED;
    }

    private void ensureOpenForWork() {
        if (status == AlertStatus.RESOLVED
                || status == AlertStatus.FALSEPOSITIVE
                || status == AlertStatus.CLOSED) {
            throw new IllegalStateException(
                    "A resolved or closed alert cannot be reassigned");
        }
    }

    private static void validateActorAndTime(
            String actor,
            Instant actionTime) {

        if (isBlank(actor) || actionTime == null) {
            throw new IllegalArgumentException(
                    "Actor and action timestamp are required");
        }
    }

    private static boolean isBlank(String value) {
        return value == null || value.isBlank();
    }

    private static String normalizeOptional(String value) {
        return isBlank(value) ? null : value.trim();
    }

    @PrePersist
    protected void onCreate() {
        Instant now = Instant.now();
        createdAt = now;
        updatedAt = now;
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = Instant.now();
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getAlertRef() {
        return alertRef;
    }

    public void setAlertRef(String alertRef) {
        this.alertRef = alertRef;
    }

    public RiskAssessmentEntity getRiskAssessment() {
        return riskAssessment;
    }

    public void setRiskAssessment(RiskAssessmentEntity riskAssessment) {
        this.riskAssessment = riskAssessment;
    }

    public String getCorrelationKey() {
        return correlationKey;
    }

    public void setCorrelationKey(String correlationKey) {
        this.correlationKey = correlationKey;
    }

    public String getDeduplicationKey() {
        return deduplicationKey;
    }

    public void setDeduplicationKey(String deduplicationKey) {
        this.deduplicationKey = deduplicationKey;
    }

    public RuleDomain getDomain() {
        return domain;
    }

    public void setDomain(RuleDomain domain) {
        this.domain = domain;
    }

    public AlertSeverity getSeverity() {
        return severity;
    }

    public void setSeverity(AlertSeverity severity) {
        this.severity = severity;
    }

    public AlertStatus getStatus() {
        return status;
    }

    public void setStatus(AlertStatus status) {
        this.status = status;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getAssignedTo() {
        return assignedTo;
    }

    public void setAssignedTo(String assignedTo) {
        this.assignedTo = assignedTo;
    }

    public String getAcknowledgedBy() {
        return acknowledgedBy;
    }

    public void setAcknowledgedBy(String acknowledgedBy) {
        this.acknowledgedBy = acknowledgedBy;
    }

    public Instant getAcknowledgedAt() {
        return acknowledgedAt;
    }

    public void setAcknowledgedAt(Instant acknowledgedAt) {
        this.acknowledgedAt = acknowledgedAt;
    }

    public Instant getSlaDueAt() {
        return slaDueAt;
    }

    public void setSlaDueAt(Instant slaDueAt) {
        this.slaDueAt = slaDueAt;
    }

    public String getResolvedBy() {
        return resolvedBy;
    }

    public void setResolvedBy(String resolvedBy) {
        this.resolvedBy = resolvedBy;
    }

    public String getResolutionCode() {
        return resolutionCode;
    }

    public void setResolutionCode(String resolutionCode) {
        this.resolutionCode = resolutionCode;
    }

    public Instant getResolvedAt() {
        return resolvedAt;
    }

    public void setResolvedAt(Instant resolvedAt) {
        this.resolvedAt = resolvedAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }

    public Long getRowVersion() {
        return rowVersion;
    }

    public void setRowVersion(Long rowVersion) {
        this.rowVersion = rowVersion;
    }

    

}
